#!/usr/bin/env bash
# Device measurements of jhbase, an explicit workflow outside the gate: build
# the freestanding archive of the target's profile, link it into the HAL
# firmware in tests/device, flash the board, read the JBM report and add the
# library's code and data size from the linker map.
set -euo pipefail

JB_ROOT="$(cd "$(dirname "${BASH_SOURCE[0]}")/.." && pwd -P)"
JB_HAL="${JHBASE_HAL_ROOT:-${JB_ROOT}/../libraries/JaszczurHAL}"
JB_TOOLS="${JHBASE_TOOLS_ROOT:-${JB_ROOT}/.build/tools}"
jb_target="" jb_assembly="" jb_port="" jb_serial="" jb_flash=1 jb_timeout=60
while (($#)); do
  case "$1" in
    --target) jb_target="${2:?--target needs a name}"; shift 2 ;;
    --assembly) jb_assembly="${2:?--assembly needs a name}"; shift 2 ;;
    --port) jb_port="${2:?--port needs a device}"; shift 2 ;;
    --serial) jb_serial="${2:?--serial needs a serial number}"; shift 2 ;;
    --hal-root) JB_HAL="${2:?--hal-root needs a path}"; shift 2 ;;
    --tools-root) JB_TOOLS="${2:?--tools-root needs a path}"; shift 2 ;;
    --timeout) jb_timeout="${2:?--timeout needs seconds}"; shift 2 ;;
    --no-flash) jb_flash=0; shift ;;
    --help)
      printf '%s\n' 'Usage: scripts/measure_device.sh' \
        '         --target rp2040|rp2350-arm|rp2350-riscv|stm32g474|esp32s3' \
        '         --assembly NAME [--serial SERIAL] [--port DEVICE] [--hal-root PATH]' \
        '         [--tools-root PATH] [--timeout SECONDS] [--no-flash]' \
        '  --serial: required for RP targets, the board picotool may flash'
      exit 0 ;;
    *) printf 'Unknown argument: %s\n' "$1" >&2; exit 2 ;;
  esac
done
fail() { printf '%s\n' "$*" >&2; exit 1; }
[[ -n "$jb_assembly" ]] || fail '--assembly is required (see tests/device/device_tree.json)'
case "$jb_target" in
  rp2040) jb_profile_name=cortex-m0plus ;;
  rp2350-arm) jb_profile_name=cortex-m33 ;;
  rp2350-riscv) jb_profile_name=rp2350-riscv ;;
  stm32g474) jb_profile_name=cortex-m4 ;;
  esp32s3) jb_profile_name=esp32s3 ;;
  *) fail "Unsupported target: ${jb_target:-none}" ;;
esac
# Name an RP board: picotool and the port lookup use its serial number.
[[ "$jb_target" != rp* || -n "$jb_serial" ]] ||
  fail "--serial is required for ${jb_target} (picotool info -a shows it)"
JB_HAL="$(cd "$JB_HAL" && pwd -P)"
JB_TOOLS="$(cd "$JB_TOOLS" && pwd -P)"
jb_project="${JB_ROOT}/tests/device"
# HAL builds ESP-IDF output only below a .build directory of the project.
jb_dir="${jb_project}/.build/${jb_assembly}"
mkdir -p "${jb_dir}/generated" "${jb_dir}/artifacts"

# shellcheck source=/dev/null
source "${JB_ROOT}/third_party/riscv_toolchain_version.conf"
# shellcheck source=/dev/null
source "${JB_ROOT}/third_party/xtensa_toolchain_version.conf"
# shellcheck source=scripts/freestanding.sh
source "${JB_ROOT}/scripts/freestanding.sh"
case "$jb_target" in
  rp2350-riscv) jb_toolchain=riscv-toolchain ;;
  esp32s3) jb_toolchain=xtensa-toolchain ;;
  *) jb_toolchain="" ;;
esac
[[ -z "$jb_toolchain" ]] ||
  "${JB_ROOT}/scripts/ensure_tools.sh" --check --tools-root "$JB_TOOLS" "$jb_toolchain"
jb_profile_compile "$jb_profile_name" "${jb_dir}/lib"

# The inputs as byte arrays; char may be signed, so they are unsigned char.
{
  printf '%s\n' '/* Generated by scripts/measure_device.sh from tests/device/inputs. */' \
    '#ifndef JB_DEVICE_INPUTS_H' '#define JB_DEVICE_INPUTS_H'
  for jb_input in config numbers; do
    printf 'static const unsigned char jb_input_%s_bytes[] = {\n' "$jb_input"
    od -An -v -tx1 "${jb_project}/inputs/${jb_input}.json" | sed 's/ \([0-9a-f][0-9a-f]\)/0x\1,/g'
    printf '};\n#define jb_input_%s ((const char *)jb_input_%s_bytes)\n' "$jb_input" "$jb_input"
    printf '#define JB_INPUT_%s_LENGTH sizeof(jb_input_%s_bytes)\n' "${jb_input^^}" "$jb_input"
  done
  printf '%s\n' '#endif'
} > "${jb_dir}/generated/jb_device_inputs.h"

jb_includes="${JB_ROOT}/include;${jb_dir}/generated"
case "$jb_target" in
  esp32s3)
    jb_esp=(python3 "${JB_HAL}/scripts/build_esp_idf.py" --project "$jb_project"
      --assembly "$jb_assembly" --target esp32s3 --name jhbase_device
      --output "${jb_dir}/esp-idf" --link-library "${jb_dir}/lib/libjhbase.a"
      --include-dir "${JB_ROOT}/include" --include-dir "${jb_dir}/generated")
    "${jb_esp[0]}" "${jb_esp[1]}" build "${jb_esp[@]:2}"
    jb_map="$(find "${jb_dir}/esp-idf" -name 'jhbase_device.map' -print -quit)"
    # The archive comes from the jhbase pin; ESP-IDF must use the same GCC.
    find "${jb_dir}/esp-idf" -name compile_commands.json -print0 |
      xargs -0 grep -q "$XTENSA_TOOLCHAIN_VERSION" ||
      fail "ESP-IDF does not use the pinned Xtensa toolchain ${XTENSA_TOOLCHAIN_VERSION}"
    ;;
  *)
    jb_cmake=(-S "${JB_HAL}/cmake/jh_firmware_project" -B "${jb_dir}/cmake" -G Ninja
      "-DJH_PROJECT_DIR=${jb_project}" "-DJH_ASSEMBLY=${jb_assembly}" "-DJH_TARGET=${jb_target}"
      "-DJH_MODULE_NAME=jhbase_device" "-DJH_ARTIFACT_DIR=${jb_dir}/artifacts"
      "-DJH_LINK_LIBRARIES=${jb_dir}/lib/libjhbase.a" "-DJH_EXTRA_INCLUDES=${jb_includes}"
      -DCMAKE_EXPORT_COMPILE_COMMANDS=ON)
    if [[ "$jb_target" == stm32g474 ]]; then
      jb_cmake+=("-DCMAKE_TOOLCHAIN_FILE=${JB_HAL}/link_libraries/stm32_lib/toolchain_stm32g474.cmake")
    else
      jb_cmake+=("-DPICO_SDK_PATH=${JB_HAL}/third_party/pico-sdk"
        "-DJH_PICOTOOL_EXECUTABLE=${JB_HAL}/.build/tools/picotool/picotool")
      # The firmware is compiled by the GCC that compiled the archive.
      [[ "$jb_target" != rp2350-riscv ]] ||
        jb_cmake+=("-DPICO_TOOLCHAIN_PATH=${JB_TOOLS}/riscv-toolchain")
    fi
    cmake "${jb_cmake[@]}"
    # The archive has the profile's ABI; refuse firmware built with other
    # machine flags (-m...), as the two would not share one ABI.
    jb_machine_flags() { { grep -oE -- '(^| )-m[^ ]+' || true; } | sed 's/^ //' | sort -u; }
    jb_firmware_flags="$(grep -F -- "-c ${jb_project}/app.c\"" \
      "${jb_dir}/cmake/compile_commands.json" | jb_machine_flags)"
    jb_archive_flags="$(printf ' %s' "${JB_PROFILE_FLAGS[@]}" | jb_machine_flags)"
    [[ -n "$jb_firmware_flags" && "$jb_firmware_flags" == "$jb_archive_flags" ]] ||
      fail "Firmware flags (${jb_firmware_flags//$'\n'/ }) differ from profile" \
        "${jb_profile_name} (${jb_archive_flags//$'\n'/ })"
    cmake --build "${jb_dir}/cmake"
    jb_map="${jb_dir}/artifacts/firmware.map"
    ;;
esac
[[ -f "$jb_map" ]] || fail "No linker map found for ${jb_assembly}"

# Library bytes in the linked image, by input section of libjhbase.a members.
awk '
  function hex(text,   value, i) {
    value = 0
    for (i = 3; i <= length(text); i++) value = value * 16 + index("0123456789abcdef", tolower(substr(text, i, 1))) - 1
    return value
  }
  /^Linker script and memory map/ { mapped = 1; next }
  /^Cross Reference Table/ { exit }
  !mapped { next }
  NF == 1 && $1 ~ /^\./ { pending = $1; next }
  /libjhbase\.a\(/ && $(NF - 1) ~ /^0x/ && $(NF - 2) ~ /^0x/ {
    name = (NF >= 4) ? $1 : pending; size = hex($(NF - 1)); pending = ""
    if (name ~ /^\.(s?bss|dram0\.bss)|^COMMON/) ram += size
    else if (name ~ /^\.s?data/) { flash += size; ram += size }
    else flash += size
    next
  }
  { pending = "" }
  END { printf "JBM size flash=%d ram=%d\n", flash, ram }
' "$jb_map" > "${jb_dir}/size.txt"
((jb_flash)) || { cat "${jb_dir}/size.txt"; exit 0; }

# by_id PATTERN: the first serial port whose /dev/serial/by-id name matches.
by_id() {
  local name
  name="$(ls /dev/serial/by-id 2>/dev/null | grep -m1 -- "$1" || true)"
  [[ -z "$name" ]] || printf '/dev/serial/by-id/%s\n' "$name"
}
# find_port: the board's serial port, waiting for it to appear. The RP
# firmware's USB port carries the chip serial; the others use the probe's port.
find_port() {
  local pattern port
  case "$jb_target" in
    rp*) pattern="$jb_serial" ;;
    stm32g474) pattern=STLINK ;;
    esp32s3) pattern=Espressif ;;
  esac
  for _ in $(seq 1 40); do
    port="$(by_id "$pattern")"
    [[ -z "$port" ]] || { printf '%s\n' "$port"; return; }
    timeout 0.5 tail -f /dev/null || true
  done
  fail 'No serial port of the board appeared; pass --port'
}
[[ -n "$jb_port" || "$jb_target" == rp* ]] || jb_port="$(find_port)"
case "$jb_target" in
  rp*)
    # HAL firmware enters BOOTSEL when its USB port is closed at 1200 bps.
    jb_running="$(by_id "$jb_serial")"
    [[ -z "$jb_running" ]] || stty -F "$jb_running" 1200 hupcl 2>/dev/null || true
    jb_loaded=0
    for _ in $(seq 1 20); do
      timeout 0.5 tail -f /dev/null || true
      if "${JB_HAL}/.build/tools/picotool/picotool" load -v -x --ser "$jb_serial" \
          "${jb_dir}/artifacts/firmware.uf2"; then
        jb_loaded=1; break
      fi
    done
    ((jb_loaded)) || fail "No ${jb_target} board with serial ${jb_serial} in BOOTSEL" ;;
  stm32g474) openocd -f interface/stlink.cfg -f target/stm32g4x.cfg \
    -c "program ${jb_dir}/artifacts/firmware.elf verify reset exit" ;;
  esp32s3) "${jb_esp[0]}" "${jb_esp[1]}" flash "${jb_esp[@]:2}" --port "$jb_port" ;;
esac
[[ -n "$jb_port" ]] || jb_port="$(find_port)"
stty -F "$jb_port" 115200 raw -echo
# The firmware repeats the report every few seconds; keep one whole report.
timeout "$jb_timeout" awk '
  { sub(/\r$/, "") }
  /JBM begin/ { sub(/.*JBM /, "JBM "); report = $0 "\n"; open = 1; next }
  open && /JBM / { sub(/.*JBM /, "JBM "); report = report $0 "\n" }
  open && /JBM end/ { printf "%s", report; exit }
' < "$jb_port" > "${jb_dir}/report.txt" || true
grep -q '^JBM end' "${jb_dir}/report.txt" || fail "No complete report from ${jb_port}"
cat "${jb_dir}/size.txt" >> "${jb_dir}/report.txt"
cat "${jb_dir}/report.txt"
grep -q '^JBM end .*result=PASS' "${jb_dir}/report.txt"
